-- DacArquitectura — Tarifes mínimes of «Base de Dades», between «Altres
-- Despeses» and «Tarifa ITE»: «Tarifa Mínima Benzina» (€/km), «Tarifa Mínima
-- Hora» (€/hora) and «Tarifes CHB, CEE i CCA» (certificats, imports + IVA).
-- Each of them, and «Tarifa ITE», carries the year it belongs to.
-- Idempotent: safe to re-run.

-- Benzina, hora and the certificats' year: single-row config (id = 1) holding
-- the inputs of David's spreadsheets. The results (€/km, €/hora) are computed
-- from them in src/lib/tarifes.ts.
create table if not exists public.tarifa_minima (
  id int primary key,
  benzina_any int not null default 2026,
  preu_litre numeric(10, 4) not null default 1.392,   -- € per litre
  consum_100km numeric(10, 2) not null default 4.5,   -- litres cada 100 km
  desgast_km numeric(10, 4) not null default 0.26,    -- € de desgast i manteniment per km
  hora_any int not null default 2026,
  sou numeric(12, 2) not null default 4700,           -- € al mes
  lloguer numeric(12, 2) not null default 1035.05,    -- lloguer del despatx al mes, sense IVA
  lloguer_iva numeric(5, 2) not null default 21,      -- % d'IVA del lloguer
  dies_mes numeric(5, 2) not null default 21,         -- dies laborables al mes
  hores_dia numeric(5, 2) not null default 8,         -- hores per dia
  certificats_any int not null default 2026,
  dificultat_min numeric(5, 2) not null default 15,   -- (*) dificultat afegida: increment mínim, %
  dificultat_max numeric(5, 2) not null default 25,   -- (*) dificultat afegida: increment màxim, %
  updated_at timestamptz not null default now()
);

insert into public.tarifa_minima (id) values (1) on conflict (id) do nothing;

-- «Tarifes CHB, CEE i CCA»: one row per line, grouped as in the sheet
-- (individuals / compostes). preu is the minimum, + IVA.
create table if not exists public.tarifa_certificat (
  id bigint generated by default as identity primary key,
  grup text not null check (grup in ('individual', 'composta')),
  concepte text not null,
  preu numeric(12, 2) not null default 0,
  dificultat boolean not null default false,          -- (*) dificultat afegida
  ordre int not null default 0
);

insert into public.tarifa_certificat (grup, concepte, preu, dificultat, ordre)
select v.grup, v.concepte, v.preu, v.dificultat, v.ordre
from (values
  ('individual', 'CHB, sense visita amb cèdula anterior', 100, true, 10),
  ('individual', 'CHB, amb visita i amb o sense cèdula anterior', 150, true, 20),
  ('individual', 'CEE, amb visita amb o sense CEE anterior', 150, true, 30),
  ('individual', 'CCA, amb visita', 75, false, 40),
  ('composta', 'CHB + CEE + CA', 300, true, 50),
  ('composta', 'CHB + CEE', 250, true, 60),
  ('composta', 'CHB + CCA', 175, true, 70),
  ('composta', 'CEE + CCA', 175, true, 80)
) as v(grup, concepte, preu, dificultat, ordre)
where not exists (select 1 from public.tarifa_certificat);

